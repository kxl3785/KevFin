#!/usr/bin/env node
// Bundles the installation and setup guides into the server as a TypeScript
// module (server/src/generated/helpDocs.ts), so the in-app assistant can read
// them in every kind of build — Docker image, desktop app, from source — without
// any of them having to ship loose Markdown files.
//
//   node scripts/gen-help-docs.mjs           rewrite the module
//   node scripts/gen-help-docs.mjs --check   exit 1 if the module is out of date
//
// A server test runs --check, so editing a guide without regenerating fails CI.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'server/src/generated/helpDocs.ts');

// [source file, name the assistant sees, one-line description]
const SOURCES = [
  ['README.md', 'getting-started.md', 'Installing the desktop app, first run, connecting accounts (SimpleFIN or Plaid), adding a home, phone access, backups, updating, common questions.'],
  ['DESKTOP.md', 'desktop-app.md', 'The desktop app in detail: choosing where its data lives, the assistant\'s Claude sign-in, running and building it from source.'],
  ['DEPLOY.md', 'docker.md', 'Running KevFin as a Docker container: building the image, Synology Container Manager setup, how to reach it, automatic snapshots, updating.'],
  ['DEPLOY-SYNOLOGY.md', 'synology-portainer.md', 'Deploying to a Synology NAS as a Portainer Git stack: how a change reaches the NAS, what the assistant needs inside a container, one-time NAS prep, gotchas.'],
  ['docs/ADVANCED.md', 'advanced.md', 'Home server or NAS with Docker, Intel Mac and Linux, features in detail, encrypted snapshots, backups, sync, how the assistant works, running from source, environment variables, demo data.'],
  ['kevfin.env.example', 'environment-variables.txt', 'Every environment variable KevFin reads, with comments: port, provider keys, database path, allowed hostnames.'],
];

// Screenshots, badges and layout HTML mean nothing to a text reader.
// A line that opens with an HTML tag is layout (image tables, centred blocks).
const NOISE = /^\s*(!\[|\[!\[|<\/?[a-z])/i;

function clean(text) {
  const out = [];
  for (const line of text.replace(/\r\n/g, '\n').split('\n')) {
    if (NOISE.test(line)) continue;
    if (line.trim() === '' && out.length && out[out.length - 1].trim() === '') continue; // collapse blank runs
    out.push(line.replace(/\s+$/, ''));
  }
  while (out.length && out[out.length - 1] === '') out.pop();
  return out;
}

const docs = SOURCES.map(([src, file, desc]) => {
  const p = path.join(root, src);
  if (!existsSync(p)) throw new Error(`Missing guide: ${src}`);
  return { src, file, desc, lines: clean(readFileSync(p, 'utf8')) };
});

const body =
  `// GENERATED by scripts/gen-help-docs.mjs — do not edit by hand.\n` +
  `// Sources: ${SOURCES.map(s => s[0]).join(', ')}.\n` +
  `// After changing a guide, run \`npm run docs:help\` from the repo root.\n\n` +
  `export interface HelpDoc { file: string; source: string; desc: string; text: string }\n\n` +
  `export const HELP_DOCS: HelpDoc[] = [\n` +
  docs.map(d =>
    `  {\n    file: ${JSON.stringify(d.file)},\n    source: ${JSON.stringify(d.src)},\n    desc: ${JSON.stringify(d.desc)},\n    text: [\n` +
    d.lines.map(l => `      ${JSON.stringify(l)},`).join('\n') +
    `\n    ].join('\\n'),\n  },`).join('\n') +
  `\n];\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error('server/src/generated/helpDocs.ts is out of date. Run: npm run docs:help');
    process.exit(1);
  }
  console.log('help docs are up to date');
} else {
  mkdirSync(path.dirname(OUT), { recursive: true });
  writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(root, OUT)} (${docs.length} guides, ${docs.reduce((n, d) => n + d.lines.length, 0)} lines)`);
}
