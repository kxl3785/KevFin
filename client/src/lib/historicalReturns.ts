// Annual US market history, 1928 through the latest complete calendar year, for
// the Forecast's historical backtest ("How would this plan have done?").
//
// Sources (retrieved 24 Nov 2026; parsed by a script from the published tables,
// not typed by hand):
//   - Stocks, bonds, bills: Aswath Damodaran (NYU Stern), "Historical Returns on
//     Stocks, Bonds and Bills: 1928-2025"
//     https://pages.stern.nyu.edu/~adamodar/New_Home_Page/datafile/histretSP.html
//       stocks = "S&P 500 (includes dividends)" annual total return
//       bonds  = "US T. Bond (10-year)" annual total return (price change + coupon)
//       bills  = "3-month T.Bill" annual return
//   - Inflation: Federal Reserve Bank of Minneapolis, "Consumer Price Index,
//     1913-" (BLS CPI-U, 1982-84 = 100), the "Annual % change" column
//     https://www.minneapolisfed.org/about-us/monetary-policy/inflation-calculator/consumer-price-index-1913-
//     This is the change in the YEAR-AVERAGE index (2022 = 8.0%), not December
//     to December (2022 = 6.5%). Damodaran's web table has no inflation column.
//
// Units: every figure is a calendar-year rate as a decimal fraction, nominal
// (0.4381 = +43.81%). Source precision is 0.01% for returns and 0.1% for
// inflation; early inflation years carry extra rounding noise because the
// source index is published to one decimal (e.g. 17.2 in 1928).
//
// Update once a year: append the new row from the same two tables.

export interface HistoricalYear {
  year: number;
  stocks: number;     // S&P 500 total return
  bonds: number;      // 10-year US Treasury total return
  bills: number;      // 3-month Treasury bill return
  inflation: number;  // CPI-U, change in the annual average
}

